/* global URL, console */
import { readFileSync, writeFileSync } from "node:fs";
import OpenCC from "opencc-js";

const sourcePath = new URL("../src/i18n.jsx", import.meta.url);
const outputPath = new URL("../src/i18n-zh-hant.js", import.meta.url);
const source = readFileSync(sourcePath, "utf8");
const start = source.indexOf("const chinese = {");
const end = source.indexOf("\n};\n\nconst LanguageContext", start);

if (start === -1 || end === -1) {
  throw new Error("Could not locate the Simplified Chinese dictionary");
}

const objectLiteral = source
  .slice(start, end + 3)
  .replace("const chinese =", "return");
const simplified = Function(objectLiteral)();
const convert = OpenCC.Converter({ from: "cn", to: "twp" });
const traditional = Object.fromEntries(
  Object.entries(simplified).map(([key, value]) => [key, convert(value)]),
);

writeFileSync(
  outputPath,
  `// Generated by scripts/generate-hant-i18n.mjs. Do not edit manually.\n` +
    `export const traditionalChinese = ${JSON.stringify(traditional, null, 2)};\n`,
);

console.log(`Generated ${Object.keys(traditional).length} Traditional Chinese translations.`);
